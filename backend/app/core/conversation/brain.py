def _pack_to_prompt_dict(pack) -> Dict:
    """Convert UserContextPack (or None) to a small dict for prompt usage. Safe attributes only."""
    if pack is None:
        return {}
    qh = getattr(pack, "quiet_hours", None)
    qh_start = getattr(qh, "start", None) if qh else None
    qh_end = getattr(qh, "end", None) if qh else None
    goals = getattr(pack, "goals", None)
    goals_items = getattr(goals, "items", []) if goals else []
    lifestyle = getattr(pack, "lifestyle", None)
    lifestyle_text = getattr(lifestyle, "text", None) if lifestyle else None
    return {
        "preferred_name": getattr(pack, "preferred_name", None),
        "language": getattr(pack, "language", None),
        "timezone": getattr(pack, "timezone", None),
        "quiet_hours": {"start": qh_start, "end": qh_end},
        "engagement_level": getattr(pack, "engagement_level", None),
        "goals_items": goals_items if isinstance(goals_items, list) else [],
        "lifestyle_text": lifestyle_text,
        "daily_memory_summary": getattr(pack, "daily_memory_summary", None),
        "birth_year": getattr(pack, "birth_year", None),
        "sex": getattr(pack, "sex", None),
        "addressing_preference": getattr(pack, "addressing_preference", None),
    }


def _build_user_context_block(pack) -> str:
    """Build a short system-only context block (max ~8 lines). No sensitive raw logs."""
    if pack is None:
        return ""
    lines = ["[USER_CONTEXT]"]
    if getattr(pack, "preferred_name", None) and str(pack.preferred_name).strip():
        lines.append("Preferred name: " + str(pack.preferred_name).strip())
    if getattr(pack, "birth_year", None):
        lines.append("Birth year: " + str(pack.birth_year))
    if getattr(pack, "sex", None) and str(pack.sex).strip():
        lines.append("Sex: " + str(pack.sex).strip())
    if getattr(pack, "addressing_preference", None) and str(pack.addressing_preference).strip():
        lines.append("Addressing preference: " + str(pack.addressing_preference).strip())
    goals = getattr(pack, "goals", None)
    if goals and getattr(goals, "items", None):
        items = [str(x) for x in goals.items if x][:5]
        if items:
            lines.append("Goals: " + ", ".join(items))
    lifestyle = getattr(pack, "lifestyle", None)
    if lifestyle and getattr(lifestyle, "text", None) and str(lifestyle.text).strip():
        t = str(lifestyle.text).strip()[:200]
        if "\n" in t:
            t = t.split("\n")[0]
        lines.append("Lifestyle: " + t)
    daily = getattr(pack, "daily_memory_summary", None)
    if daily and str(daily).strip():
        lines.append("Recent: " + str(daily).strip()[:150])
    if len(lines) <= 1:
        return ""
    return "\n".join(lines[:9])


def _redact_secrets(text: str) -> str:
    """Mask likely API key fragments before logging."""
    import re

    redacted = re.sub(r"sk-[A-Za-z0-9_-]{8,}", "sk-***", text or "")
    return re.sub(r"(api[_-]?key\s*[:=]\s*)\S+", r"\1***", redacted, flags=re.IGNORECASE)


def _log_gpt_failure(exc: BaseException, *, where: str) -> None:
    """Structured GPT failure log without leaking secrets."""
    print(
        f"[BRAIN GPT_FAILURE] where={where} "
        f"error_type={type(exc).__name__} "
        f"message={_redact_secrets(str(exc))[:300]}"
    )


def _is_gpt_related_error(exc: BaseException) -> bool:
    """True when the failure should surface as gpt_failure (502) from interact router."""
    error_str = str(exc).lower()
    error_type_name = type(exc).__name__.lower()
    return (
        "openai" in error_str
        or "api key" in error_str
        or "authentication" in error_str
        or "rate limit" in error_str
        or "gpt" in error_str
        or "completion" in error_str
        or "openai" in error_type_name
        or "authenticationerror" in error_type_name
        or "apierror" in error_type_name
    )


class ConversationBrain:
    """Central decision engine for all conversation interactions"""
    
    def __init__(self, db: Session, language: str = "en"):
        self.db = db
        self.language = language
        self.memory = ConversationMemory(db)
        self.prompts = ConversationPrompts(language)
    
    def process_message(
        self,
        user_id: int,
        user_message: str,
        user_name: Optional[str] = None,
        *,
        notification_context: Optional[dict] = None,
    ) -> Dict[str, any]:
        """
        Process user message and generate Sedi's response.
        
        Flow:
        1. Get current conversation stage
        2. Build conversation context
        3. Generate response using prompts
        4. Save conversation to memory
        5. Check for stage transition
        6. Return response with metadata
        
        Args:
            user_id: User ID
            user_message: User's message
        
        Returns:
            Dict with:
            - message: Sedi's response text
            - language: Language code
            - stage: Current conversation stage
            - metadata: Optional metadata (tone, intent, etc.)
        """
        # TEMP DEBUG: Log entry
        print(f"[BRAIN DEBUG] ===== PROCESSING MESSAGE =====")
        print(f"[BRAIN DEBUG] user_id={user_id}, message={user_message[:50]}...")
        
        try:
            # Validate user exists
            user = self.db.query(User).filter(User.id == user_id).first()
            if not user:
                print(f"[BRAIN DEBUG] ERROR: User not found")
                return {
                    "message": self._get_error_message("user_not_found"),
                    "language": self.language,
                    "stage": None,
                    "error": "User not found"
                }
            
            # EXPERIENCE STABILITY: Strict orchestration order
            # 1. IDENTIFY: Ensure user_id is valid (already validated above)
            # 2. LOAD: Get current state (stage, memory count, facts)
            current_stage = get_stage(user_id, self.db)
            current_memory_count = self.memory.get_conversation_count(user_id)
            print(f"[BRAIN DEBUG] Current stage: {current_stage.value}, memory_count: {current_memory_count}")
            
            # 3. BUILD MESSAGES: Build messages explicitly without context dependency
            from backend.app.core.conversation.prompts import client as gpt_client, build_system_prompt_with_context
            from backend.app.core.conversation.persona_policy_v1 import PersonaPolicyV1

            # Stage 23 Step 3: User-aware system prompt (Persona v1 + context block). Fail-open if context fetch fails.
            pack = None
            try:
                from backend.app.services.user_context import UserContextService
                pack = UserContextService(self.db).get_user_context(user_id)
            except Exception as ctx_err:
                print(f"[BRAIN WARNING] UserContext fetch failed (non-critical, proceeding): {ctx_err}")

            lang = PersonaPolicyV1.resolve_language(
                (getattr(pack, "language", None) if pack else None) or self.language
            )
            preferred_name = getattr(pack, "preferred_name", None) if pack else None
            context_block = _build_user_context_block(pack)
            system_prompt_content = build_system_prompt_with_context(lang, preferred_name, context_block)

            messages = [
                {"role": "system", "content": system_prompt_content}
            ]
            # User Knowledge: stable baseline + facts (compact, after main system, before history)
            user_knowledge_str = _build_user_knowledge_context(self.db, user_id)
            if user_knowledge_str:
                messages.append({"role": "system", "content": user_knowledge_str})

            # Stage 17.5: Optional Local RAG context (gated; no behavior change when disabled)
            _maybe_append_local_rag_context(messages, self.db, user_id, user_message, self.language)

            # Stage 23 Step 5: Facts-anchored RAG context (fail-open; medical risk gate)
            _maybe_append_rag_context_v1(messages, self.db, user_id, user_message, lang)

            # Gate 3: care context for medical intents (canonical stores only)
            _maybe_append_gate3_care_context(messages, self.db, user_id, user_message, lang)

            notification_block = _format_notification_context_block(notification_context)
            if notification_block:
                messages.append({"role": "system", "content": notification_block})

            # Optionally append history if available (non-blocking)
            try:
                recent_messages = self.memory.get_recent_messages(user_id, limit=10)
                for msg in reversed(recent_messages):  # Oldest first
                    if msg.user_message and msg.sedi_response:
                        messages.append({"role": "user", "content": msg.user_message})
                        messages.append({"role": "assistant", "content": msg.sedi_response})
            except Exception as history_error:
                # Memory failure is non-critical - continue without history
                print(f"[BRAIN WARNING] Could not load history (non-critical): {history_error}")
            
            # Always append current user message
            messages.append({"role": "user", "content": user_message})
            
            print(f"[BRAIN DEBUG] Messages built - count: {len(messages)}")
            
            # Check if we need to extract user name from conversation
            # Build minimal context_data for helper methods only
            minimal_context = {
                "user_id": user_id,
                "stage": current_stage.value,
                "conversation_count": current_memory_count,
                "recent_messages": []
            }
            try:
                recent_messages_list = self.memory.get_recent_messages(user_id, limit=5)
                minimal_context["recent_messages"] = [
                    {"sedi": msg.sedi_response or ""} for msg in recent_messages_list
                ]
            except:
                pass
            detected_name = self._extract_name_from_message(user_id, user_message, current_stage, minimal_context)

            # Gate 3: emergency/high-risk short-circuit before GPT
            gate3_template = _gate3_check_emergency_short_circuit(user_message, lang)
            if gate3_template:
                sedi_response = gate3_template
                print("[BRAIN] Gate3 safety short-circuit applied")
            else:
                # 4. GENERATE: Call GPT directly with messages
                print(f"[BRAIN] ===== BEFORE GPT CALL =====")
                print(f"[BRAIN] User ID: {user_id}")
                print(f"[BRAIN] User message: '{user_message[:100]}...'")
                print(f"[BRAIN] Language: {self.language}")
                print(f"[BRAIN] Stage: {current_stage.value}")
                print(f"[BRAIN] Messages count: {len(messages)}")
                print(f"[BRAIN] ===== END BEFORE GPT =====")
                try:
                    completion = gpt_client.responses.create(
                        model="gpt-4o-mini",
                        input=messages
                    )
                    sedi_response = completion.output_text.strip()
                    sedi_response = _gate3_validate_assistant_response(sedi_response, lang)
                    print(f"[BRAIN DEBUG] Response generated (length={len(sedi_response)})")
                except Exception as gpt_exception:
                    _log_gpt_failure(gpt_exception, where="process_message.responses_create")
                    raise

            # STEP 4: SAVE: Save conversation to memory (updates memory_count)
            # CRITICAL: Memory is OPTIONAL - memory failure must NOT block chat
            mem = None
            try:
                mem = self.memory.save_conversation(
                    user_id=user_id,
                    user_message=user_message,
                    sedi_response=sedi_response,
                    language=self.language
                )
                print(f"[BRAIN DEBUG] ✅ Conversation saved - new memory_count: {self.memory.get_conversation_count(user_id)}")
            except Exception as memory_error:
                # STEP 4: Memory failure is non-critical - log but continue
                print(f"[BRAIN WARNING] ⚠️ Memory save failed (non-critical): {memory_error}")
                print(f"[BRAIN WARNING] Chat response will still be returned to user")
                import traceback
                print(f"[BRAIN WARNING] Memory error traceback: {traceback.format_exc()}")
                # Continue - don't block chat response

            # Gate 2: KC extraction ingress (replaces legacy user_fact_candidates primary writes)
            try:
                from backend.app.services.knowledge.conversation_extraction_service import process_message as kc_process_message
                kc_process_message(
                    db=self.db,
                    user_id=user_id,
                    text=user_message,
                    language=self.language or "fa",
                    source_message_id=str(mem.id) if mem else None,
                )
            except Exception as extract_err:
                print(f"[BRAIN] KC extract (non-critical): {extract_err}")

            # 6. TRANSITION: Check for stage transition (AFTER save - uses updated memory_count)
            new_stage = transition_stage(current_stage, user_id, self.db)
            print(f"[BRAIN DEBUG] Stage transition: {current_stage.value} -> {new_stage.value}")
            
            # Get updated conversation count
            updated_conversation_count = self.memory.get_conversation_count(user_id)
            
            print(f"[BRAIN DEBUG] ===== MESSAGE PROCESSED =====")
            
            # Build metadata with updated state
            metadata = {
                "stage": new_stage.value,
                "conversation_count": updated_conversation_count,
                "tone": self._infer_tone(sedi_response),
                "stage_transitioned": new_stage != current_stage
            }
            
            return {
                "message": sedi_response,
                "language": self.language,
                "stage": new_stage.value,  # Return NEW stage (after save and transition)
                "metadata": metadata,
                "detected_name": detected_name  # Name detected from conversation (to update frontend)
            }
        except Exception as e:
            # Log the error for debugging
            print(f"[BRAIN ERROR] Exception in process_message: {e}")
            print(f"[BRAIN ERROR] Exception type: {type(e).__name__}")
            import traceback
            print(f"[BRAIN ERROR] Traceback: {traceback.format_exc()}")

            if _is_gpt_related_error(e):
                _log_gpt_failure(e, where="process_message.outer_re_raise")
                raise

            # Non-GPT failures: return a user-friendly error message (HTTP 200 legacy path)
            error_messages = {
                "en": "I'm sorry, I encountered an error processing your message. Please try again.",
                "fa": "متاسفم، در پردازش پیام شما خطایی رخ داد. لطفاً دوباره تلاش کنید.",
                "ar": "عذراً، حدث خطأ في معالجة رسالتك. يرجى المحاولة مرة أخرى."
            }
            
            error_message = error_messages.get(self.language, error_messages["en"])
            
            # Try to get current stage for response
            try:
                current_stage = get_stage(user_id, self.db)
                stage_value = current_stage.value
            except:
                stage_value = "FIRST_CONTACT"
            
            return {
                "message": error_message,
                "language": self.language,
                "stage": stage_value,
                "metadata": {
                    "error": True,
                    "error_type": type(e).__name__
                }
            }
    
    def get_initial_message(self, user_id: int, user_name: Optional[str], language: str) -> str:
        """
        Generate initial message after onboarding.
        Uses GPT with Sedi's knowledge base to introduce Sedi and explain what she does.
        
        Args:
            user_id: User ID from database
            user_name: User's name from frontend (optional, for personalization)
            language: Language code ('en', 'fa', 'ar')
        """
        from backend.app.core.conversation.sedi_knowledge_base import build_complete_sedi_context
        # VERIFY: Same client used in onboarding and chat
        from backend.app.core.conversation.prompts import client as gpt_client
