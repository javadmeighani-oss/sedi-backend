_USER_KNOWLEDGE_MAX_CHARS = 1200
_NOTIFICATION_CONTEXT_MAX_CHARS = 2000


def _format_notification_context_block(notification_context: Optional[Mapping[str, Any]]) -> Optional[str]:
    """Format safe notification context for internal GPT system prompt injection."""
    if not notification_context:
        return None

    lines = [
        "[NOTIFICATION_CONTEXT]",
        "The user opened chat from a prior notification. Continue naturally from this context.",
        "Do not provide medical diagnosis, prescribe treatments, or suggest medication dose changes.",
        "If risk is high or critical, encourage contacting a qualified clinician when appropriate.",
    ]

    for key in (
        "category",
        "template_key",
        "risk_level",
        "source_type",
        "source_id",
        "notification_title",
        "notification_summary",
    ):
        value = notification_context.get(key)
        if value is not None and str(value).strip():
            lines.append(f"{key}: {str(value).strip()[:256]}")

    hints = notification_context.get("context_hints")
    if isinstance(hints, dict):
        for hint_key, hint_value in hints.items():
            if hint_value is not None and str(hint_value).strip():
                lines.append(f"hint_{hint_key}: {str(hint_value).strip()[:256]}")

    text = "\n".join(lines)
    if len(text) > _NOTIFICATION_CONTEXT_MAX_CHARS:
        text = text[: _NOTIFICATION_CONTEXT_MAX_CHARS - 3] + "..."
    return text


def _build_user_knowledge_context(db: Session, user_id: int) -> Optional[str]:
    """Load UserProfileKnowledge + UserFact; return [USER_PROFILE] string (max 1200 chars) or None."""
    try:
        from backend.app import models
        lines = []
        profile = (
            db.query(models.UserProfileKnowledge)
            .filter(models.UserProfileKnowledge.user_id == user_id)
            .first()
        )
        if profile:
            if profile.baseline_summary and profile.baseline_summary.strip():
                lines.append("baseline: " + profile.baseline_summary.strip())
            if profile.goals_json and profile.goals_json.strip():
                lines.append("goals: " + profile.goals_json.strip()[:300])
            if profile.constraints_json and profile.constraints_json.strip():
                lines.append("constraints: " + profile.constraints_json.strip()[:300])
            if profile.preferences_json and profile.preferences_json.strip():
                lines.append("preferences: " + profile.preferences_json.strip()[:300])
        facts = (
            db.query(models.UserFact)
            .filter(models.UserFact.user_id == user_id)
            .order_by(models.UserFact.updated_at.desc())
            .limit(30)
            .all()
        )
        fact_parts = []
        for f in facts:
            val = (f.value_json or "").strip()
            if len(val) > 80:
                val = val[:77] + "..."
            fact_parts.append(f"{f.key}={val}")
        if fact_parts:
            lines.append("facts: " + "; ".join(fact_parts))
        if not lines:
            return None
        text = "[USER_PROFILE]\n" + "\n".join(lines)
        if len(text) > _USER_KNOWLEDGE_MAX_CHARS:
            text = text[:_USER_KNOWLEDGE_MAX_CHARS - 3] + "..."
        return text
    except Exception as e:
        print(f"[BRAIN WARNING] User knowledge load failed (non-critical): {e}")
        return None


def _maybe_append_local_rag_context(messages: list, db, user_id: int, user_message: str, language: str) -> None:
    """Stage 17.5: Append [LOCAL_CONTEXT] block when RAG_LOCAL_ENABLED. No-op otherwise."""
    import os
    if not os.environ.get("RAG_LOCAL_ENABLED", "false").lower() in ("true", "1", "yes"):
        return
    try:
        from backend.app.services.local_rag.provider_router import retrieve as rag_retrieve
        result = rag_retrieve(db, user_id, user_message or "chat", language)
        if result.combined_text and len(result.combined_text.strip()) > 10:
            block = "[LOCAL_CONTEXT]\n" + result.combined_text.strip()
            messages.append({"role": "system", "content": block})
    except Exception:
        pass


def _maybe_append_rag_context_v1(
    messages: list,
    db,
    user_id: int,
    user_message: str,
    language: str,
    rag_context_max_chars: int = 1200,
) -> None:
    """
    Stage 23 Step 5: Optional facts-anchored [RAG_CONTEXT] block.
    Builds RagContextPack; if rag_allowed(user_message), appends serialized pack + optional
    local RAG retrieval (capped). Else appends short safety note. Fail-open.
    """
    import os
    try:
        from backend.app.services.rag_context import (
            build_rag_context_pack,
            rag_allowed,
            serialize_rag_pack_for_context,
        )
    except ImportError:
        try:
            from app.services.rag_context import (
                build_rag_context_pack,
                rag_allowed,
                serialize_rag_pack_for_context,
            )
        except ImportError:
            return
    try:
        rag_pack = build_rag_context_pack(db, user_id, fallback_language=language)
        lang = rag_pack.language or language or "en"
        if not rag_allowed(user_message or "", lang):
            safety_note = (
                "[RAG_CONTEXT]\nGeneral info only. If this is a medical emergency or serious concern, "
                "please contact a clinician or emergency services."
            )
            messages.append({"role": "system", "content": safety_note})
            return
        summary = serialize_rag_pack_for_context(rag_pack, max_chars=rag_context_max_chars)
        content = summary
        if os.environ.get("RAG_LOCAL_ENABLED", "false").lower() in ("true", "1", "yes"):
            try:
                from backend.app.services.local_rag.provider_router import retrieve as rag_retrieve
                result = rag_retrieve(db, user_id, user_message or "chat", lang)
                if result and getattr(result, "combined_text", None) and result.combined_text.strip():
                    extra = result.combined_text.strip()[:800]
                    content = (summary + "\n" + extra).strip()
            except Exception:
                pass
        if len(content) > rag_context_max_chars:
            content = content[: rag_context_max_chars - 3] + "..."
        if content.strip():
            messages.append({"role": "system", "content": "[RAG_CONTEXT]\n" + content.strip()})
    except Exception as e:
        print(f"[BRAIN WARNING] RAG context v1 failed (non-critical): {e}")


def _gate3_check_emergency_short_circuit(user_message: str, language: str) -> Optional[str]:
    """Gate 3: fixed emergency template — no creative LLM."""
    try:
        from backend.app.services.gate3.safety_core import RiskClassifier, SafetyPolicy
        risk = RiskClassifier().classify(user_message or "", language or "fa")
        if risk.risk_level == "emergency":
            return SafetyPolicy().response_for_level("emergency", language or "fa")
        if risk.risk_level == "high":
            return SafetyPolicy().response_for_level("high", language or "fa")
    except Exception as e:
        print(f"[BRAIN WARNING] Gate3 emergency check failed (non-critical): {e}")
    return None


def _maybe_append_gate3_care_context(messages: list, db, user_id: int, user_message: str, language: str) -> None:
    """Gate 3: canonical care context for medical/care intents only."""
    try:
        from backend.app.services.gate3.medical_intent import is_medical_care_intent
        from backend.app.services.gate3.care_intelligence import build_care_context
        if not is_medical_care_intent(user_message, language):
            return
        ctx = build_care_context(db, user_id, language, query_hint=user_message)
        # Compact block — no raw chat, no caregiver phone
        lines = ["[CARE_CONTEXT] Canonical user care data (educational use only):"]
        if ctx.get("goals"):
            lines.append("Goals: " + ", ".join(g["title"] for g in ctx["goals"][:3] if g.get("title")))
        if ctx.get("restrictions"):
            lines.append("Restrictions: " + ", ".join(r["title"] for r in ctx["restrictions"][:3] if r.get("title")))
        if ctx.get("upcoming_events"):
            lines.append("Upcoming: " + "; ".join(
                f"{e.get('title')} ({e.get('event_type')})" for e in ctx["upcoming_events"][:3]
            ))
        snippets = ctx.get("knowledge_snippets") or []
        if snippets:
            lines.append("Curated knowledge (cite sources):")
            for sn in snippets[:2]:
                cit = sn.get("citation") or {}
                lines.append(f"- [{cit.get('label', 'source')}] {sn.get('content', '')[:200]}")
        block = "\n".join(lines)[:1200]
        messages.append({"role": "system", "content": block})
    except Exception as e:
        print(f"[BRAIN WARNING] Gate3 care context failed (non-critical): {e}")


